"""Audit native tool timing without attributing untimed model work to a tool."""

import argparse
import json
from collections import Counter
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument("run", type=Path)
parser.add_argument("output", type=Path)
args = parser.parse_args()
run = args.run.resolve()
calls = [json.loads(line) for line in (run / "mcp-calls.jsonl").read_text().splitlines()]
outbox = []
for path in sorted((run / "outbox").glob("*.json")):
    outbox.append((int(path.stem) / 1e9, json.loads(path.read_text()), path.name))
commands = [json.loads(line) for line in (run / "commands.jsonl").read_text().splitlines()]
events = []
unmatched = []
for index, call in enumerate(calls):
    if call["tool"] not in ("execute_chunk", "measure_rim"):
        continue
    match = next(
        (
            item
            for item in outbox
            if item[1] == call["result"]
            or {k: v for k, v in item[1].items() if k != "observation"} == call["result"]
        ),
        None,
    )
    if match is None:
        unmatched.append(dict(index=index, tool=call["tool"]))
        continue
    outbox.remove(match)
    submitted, receipt, filename = match
    previous = calls[index - 1] if index else None
    events.append(
        dict(
            tool=call["tool"],
            command=call["request"].get("rim_measure", {}).get("command"),
            subgoal=call["request"].get("subgoal"),
            step_before=receipt.get("step_before"),
            step_after=receipt.get("step_after"),
            submitted_epoch=submitted,
            audit_completed_epoch=call["time"],
            submission_to_audit_seconds=call["time"] - submitted,
            backend_seconds=receipt.get("wall_seconds"),
            vendor_reported_cpu_seconds=receipt.get("result", {}).get("cpu_s"),
            preceding_mcp_tool=previous["tool"] if previous else None,
            since_previous_mcp_completion_seconds=(
                submitted - previous["time"] if previous else None
            ),
            outbox=filename,
        )
    )
measurements = [event for event in events if event["tool"] == "measure_rim"]
agent_errors = []
for line in (run / "agent-events.jsonl").read_text().splitlines():
    event = json.loads(line)
    item = event.get("item", {})
    if event.get("type") == "error" or item.get("type") == "error":
        agent_errors.append(event.get("message", item.get("message")))
report = dict(
    run=str(run),
    role="development_timing_audit_only",
    provenance="Submission epochs are the native outbox request filenames generated by time.time_ns; completion epochs are actual mcp-calls audit records. Backend durations are the original native command receipts.",
    limitations=[
        "Submission-to-audit includes simulator processing, RGB snapshot saves and IPC; it is not pure geometry CPU time.",
        "Time before a request includes model thinking, vision interpretation, local calculations and unrecorded non-MCP work. It cannot be attributed solely to selecting rim points.",
        "A measurement-related interval or high call count is not a causal estimate of avoidable wall time.",
    ],
    matched_native_commands=len(events),
    unmatched_calls=unmatched,
    native_backend_command_count=len(commands),
    mcp_tool_counts=dict(Counter(call["tool"] for call in calls)),
    measurement_submission_to_audit_seconds=sum(
        event["submission_to_audit_seconds"] for event in measurements
    ),
    measurement_backend_seconds=sum(event["backend_seconds"] for event in measurements),
    intercall_time_immediately_preceding_measurements_seconds=sum(
        event["since_previous_mcp_completion_seconds"] or 0 for event in measurements
    ),
    largest_intervals_before_native_commands=sorted(
        events,
        key=lambda event: event["since_previous_mcp_completion_seconds"] or 0,
        reverse=True,
    )[:5],
    agent_error_records_without_timestamps=agent_errors,
    events=events,
)
args.output.parent.mkdir(parents=True, exist_ok=True)
args.output.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n")
print(json.dumps({key: value for key, value in report.items() if key != "events"}))
