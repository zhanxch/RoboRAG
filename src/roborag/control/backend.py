"""The delta executor's backend contract, independent of RoboDojo internals."""

from typing import Any, Protocol


class ArmState(Protocol):
    def ee(self) -> Any: ...


class ActionBackend(Protocol):
    geometry: Any

    @property
    def step(self) -> int: ...

    @property
    def over(self) -> bool: ...

    def arm(self, side: str) -> ArmState: ...
    def gripper_command_key(self, side: str) -> str: ...
    def dispatch_action(self, command: dict) -> None: ...
    def invalidate_observation(self) -> None: ...
    def update_arm_targets(self, side: str, gripper: float) -> None: ...
    def record_action(self, record: dict) -> None: ...
